//go:build !windows && !darwin

package downloaddir

import (
	"os"
	"path/filepath"
	"testing"
)

func writeUserDirs(t *testing.T, configHome, content string) {
	t.Helper()
	if err := os.MkdirAll(configHome, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(configHome, "user-dirs.dirs"), []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestXDGDownloadDir(t *testing.T) {
	home := t.TempDir()
	configHome := t.TempDir()
	writeUserDirs(t, configHome, "# generated by xdg-user-dirs-update\nXDG_DOWNLOAD_DIR=\"$HOME/下载\"\n")

	got, ok := xdgDownloadDir(configHome, home)
	if !ok {
		t.Fatal("XDG_DOWNLOAD_DIR was not detected")
	}
	if want := filepath.Join(home, "下载"); got != want {
		t.Fatalf("xdgDownloadDir = %q, want %q", got, want)
	}
}

func TestXDGDownloadDirRejectsRelativeAndHomePaths(t *testing.T) {
	home := t.TempDir()
	for name, content := range map[string]string{
		"relative": `XDG_DOWNLOAD_DIR="relative/downloads"`,
		"home":     `XDG_DOWNLOAD_DIR="$HOME/"`,
	} {
		t.Run(name, func(t *testing.T) {
			configHome := t.TempDir()
			writeUserDirs(t, configHome, content)
			if got, ok := xdgDownloadDir(configHome, home); ok {
				t.Fatalf("xdgDownloadDir = %q, want invalid entry ignored", got)
			}
		})
	}
}

func TestDefaultUsesXDGDownloadDir(t *testing.T) {
	home := t.TempDir()
	configHome := t.TempDir()
	writeUserDirs(t, configHome, "XDG_DOWNLOAD_DIR=\"$HOME/my-downloads\"\n")
	t.Setenv("HOME", home)
	t.Setenv("XDG_CONFIG_HOME", configHome)

	if got, want := Default(), filepath.Join(home, "my-downloads"); got != want {
		t.Fatalf("Default = %q, want %q", got, want)
	}
}
